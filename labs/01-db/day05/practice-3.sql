-- [1] 섹션별 평균 조회수 중 가장 높은 값을 구하세요.
--     힌트: 안쪽에서 섹션별 평균을 구하고, 바깥에서 MAX 를 씁니다.
--           FROM (SELECT section, AVG(views) AS 섹션평균 FROM ... GROUP BY section) AS t




-- [2] 기사를 30건 이상 쓴 기자들의 「평균 기사 수」를 구하세요.
--     (안쪽에서 기자별 건수를 구하고 HAVING 으로 거른 뒤, 바깥에서 평균)




-- [3] 부서별 평균 조회수가 전체 평균보다 높은 부서만 조회하세요.
--     (부서 · 부서평균, 높은 순)
--     힌트: 파생 테이블 + WHERE 안에 또 서브쿼리




-- ============================================================
--  반드시 실행할 것 — 오류를 눈으로 직접 볼 것
-- ============================================================

-- [4] 아래 쿼리는 오류가 납니다. 무엇이 빠졌는지 찾아보세요.

SELECT AVG(섹션평균)
FROM   (SELECT section, AVG(views) AS 섹션평균
        FROM   articles
        GROUP BY section);

