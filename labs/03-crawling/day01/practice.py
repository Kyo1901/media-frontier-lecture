#
#    (가) r.encoding 을 "utf-8" 로 정해 준 다음 r.text 를 쓴다
#    (나) r.text 대신 r.content(바이트) 를 쓴다
#
#  «여야» 라는 글자가 본문에 있는지 각각 확인해서 True/False 로 출력하세요.
